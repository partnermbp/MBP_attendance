-- Manager access assignments and Telegram group analytics.
-- Apply in the Supabase SQL editor after reviewing the existing project schema.
-- This migration does not update or delete attendance rows.

create table if not exists public.manager_employee_assignments (
  manager_id uuid not null references public.profiles(id) on delete cascade,
  employee_id uuid not null references public.profiles(id) on delete cascade,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  primary key (manager_id, employee_id),
  constraint manager_employee_not_self check (manager_id <> employee_id)
);

create index if not exists manager_employee_assignments_employee_idx
  on public.manager_employee_assignments(employee_id);

alter table public.manager_employee_assignments enable row level security;

create or replace function public.is_active_admin()
returns boolean language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.active = true and lower(p.role) = 'admin'
  );
$$;

create or replace function public.is_assigned_manager(target_employee uuid)
returns boolean language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1 from public.manager_employee_assignments a
    join public.profiles p on p.id = a.manager_id
    where a.manager_id = auth.uid()
      and a.employee_id = target_employee
      and p.active = true and lower(p.role) = 'manager'
  );
$$;

drop policy if exists "Admins manage assignments" on public.manager_employee_assignments;
create policy "Admins manage assignments"
  on public.manager_employee_assignments for all
  to authenticated
  using (public.is_active_admin())
  with check (
    public.is_active_admin()
    and exists (select 1 from public.profiles m where m.id = manager_id and lower(m.role) = 'manager' and m.active = true)
    and exists (select 1 from public.profiles e where e.id = employee_id and lower(e.role) <> 'admin' and e.active = true)
  );

drop policy if exists "Managers read own assignments" on public.manager_employee_assignments;
create policy "Managers read own assignments"
  on public.manager_employee_assignments for select
  to authenticated using (manager_id = auth.uid());

-- Telegram data is ingested by a server-side webhook using the service role.
create table if not exists public.telegram_groups (
  id bigint generated by default as identity primary key,
  telegram_chat_id bigint not null unique,
  title text not null,
  enabled boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.telegram_group_members (
  id bigint generated by default as identity primary key,
  telegram_chat_id bigint not null references public.telegram_groups(telegram_chat_id) on delete cascade,
  telegram_user_id bigint not null,
  username text,
  display_name text,
  profile_id uuid references public.profiles(id) on delete set null,
  is_active boolean not null default true,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  unique (telegram_chat_id, telegram_user_id)
);

create table if not exists public.telegram_messages (
  id bigint generated by default as identity primary key,
  telegram_chat_id bigint not null references public.telegram_groups(telegram_chat_id) on delete cascade,
  telegram_message_id bigint not null,
  telegram_user_id bigint,
  username text,
  display_name text,
  message_text text,
  message_date timestamptz not null,
  reply_to_message_id bigint,
  edited_at timestamptz,
  is_deleted boolean not null default false,
  message_kind text not null default 'text',
  raw_update jsonb,
  unique (telegram_chat_id, telegram_message_id)
);

create index if not exists telegram_messages_chat_date_idx
  on public.telegram_messages(telegram_chat_id, message_date desc);
create index if not exists telegram_messages_reply_idx
  on public.telegram_messages(telegram_chat_id, reply_to_message_id);

create table if not exists public.telegram_reactions (
  id bigint generated by default as identity primary key,
  telegram_chat_id bigint not null,
  telegram_message_id bigint not null,
  reaction jsonb not null,
  updated_at timestamptz not null default now(),
  unique (telegram_chat_id, telegram_message_id, reaction)
);

create table if not exists public.telegram_response_metrics (
  id bigint generated by default as identity primary key,
  telegram_chat_id bigint not null,
  question_message_id bigint not null,
  question_user_id bigint,
  first_reply_message_id bigint,
  first_reply_user_id bigint,
  response_seconds integer,
  calculated_at timestamptz not null default now(),
  unique (telegram_chat_id, question_message_id)
);

create table if not exists public.telegram_admin_audit (
  id bigint generated by default as identity primary key,
  actor_profile_id uuid references public.profiles(id) on delete set null,
  action text not null,
  target_type text not null,
  target_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.telegram_groups enable row level security;
alter table public.telegram_group_members enable row level security;
alter table public.telegram_messages enable row level security;
alter table public.telegram_reactions enable row level security;
alter table public.telegram_response_metrics enable row level security;
alter table public.telegram_admin_audit enable row level security;

-- Admins can inspect all company Telegram analytics. Managers can inspect only
-- chats containing at least one employee assigned to them; employee identities
-- are linked explicitly in telegram_group_members.profile_id.
drop policy if exists "Admins read telegram groups" on public.telegram_groups;
create policy "Admins read telegram groups" on public.telegram_groups
  for select to authenticated using (public.is_active_admin());

drop policy if exists "Authorized staff read telegram members" on public.telegram_group_members;
create policy "Authorized staff read telegram members" on public.telegram_group_members
  for select to authenticated using (
    public.is_active_admin()
    or (profile_id is not null and public.is_assigned_manager(profile_id))
  );

drop policy if exists "Authorized staff read telegram messages" on public.telegram_messages;
create policy "Authorized staff read telegram messages" on public.telegram_messages
  for select to authenticated using (
    public.is_active_admin()
    or exists (
      select 1 from public.telegram_group_members gm
      where gm.telegram_chat_id = telegram_messages.telegram_chat_id
        and gm.profile_id is not null
        and public.is_assigned_manager(gm.profile_id)
    )
  );

drop policy if exists "Authorized staff read telegram reactions" on public.telegram_reactions;
create policy "Authorized staff read telegram reactions" on public.telegram_reactions
  for select to authenticated using (
    public.is_active_admin()
    or exists (
      select 1 from public.telegram_group_members gm
      where gm.telegram_chat_id = telegram_reactions.telegram_chat_id
        and gm.profile_id is not null
        and public.is_assigned_manager(gm.profile_id)
    )
  );

drop policy if exists "Authorized staff read telegram response metrics" on public.telegram_response_metrics;
create policy "Authorized staff read telegram response metrics" on public.telegram_response_metrics
  for select to authenticated using (
    public.is_active_admin()
    or exists (
      select 1 from public.telegram_group_members gm
      where gm.telegram_chat_id = telegram_response_metrics.telegram_chat_id
        and gm.profile_id is not null
        and public.is_assigned_manager(gm.profile_id)
    )
  );

drop policy if exists "Admins read telegram audit" on public.telegram_admin_audit;
create policy "Admins read telegram audit" on public.telegram_admin_audit
  for select to authenticated using (public.is_active_admin());

