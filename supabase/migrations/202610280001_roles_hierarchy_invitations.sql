-- MBP Attendance: role management, multi-level hierarchy and manager-linked invitations.
-- Apply in the Supabase SQL Editor before enabling the related UI.
create extension if not exists pgcrypto with schema extensions;

create or replace function public.is_hierarchy_manager(target_profile uuid default auth.uid())
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = target_profile and p.active = true
      and lower(replace(p.role::text, '_', ' ')) in ('middle','senior','team leader','manager')
  );
$$;

create or replace function public.set_employee_role(target_profile uuid, new_role text)
returns void
language plpgsql security definer
set search_path = public
as $$
declare normalized_role text := lower(trim(replace(new_role, '_', ' ')));
begin
  if not public.is_active_admin() then
    raise exception 'Only active admins can assign roles' using errcode = '42501';
  end if;
  if normalized_role not in ('junior','middle','senior','team leader','telemarketing') then
    raise exception 'Unsupported employee role';
  end if;
  update public.profiles
    set role = (case normalized_role when 'team leader' then 'team_leader' else normalized_role end)::public.app_role
    where id = target_profile and active = true and lower(role::text) <> 'admin';
  if not found then
    raise exception 'Employee not found, inactive, or protected admin account';
  end if;
  insert into public.telegram_admin_audit(actor_profile_id, action, target_type, target_id, details)
  values (auth.uid(), 'role_changed', 'profile', target_profile::text, jsonb_build_object('role', normalized_role));
end;
$$;

-- Invitations are one-use, time-limited and store only a hash of the bearer token.
create table if not exists public.manager_invitations (
  id bigint generated by default as identity primary key,
  token_hash text not null unique,
  invited_by uuid not null references public.profiles(id) on delete cascade,
  invited_role text not null default 'junior'
    check (lower(replace(invited_role, '_', ' ')) in ('junior','middle','senior','team leader','telemarketing')),
  expires_at timestamptz not null default (now() + interval '7 days'),
  redeemed_by uuid references public.profiles(id) on delete set null,
  redeemed_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists manager_invitations_invited_by_idx on public.manager_invitations(invited_by);
alter table public.manager_invitations enable row level security;
drop policy if exists "Admins read manager invitations" on public.manager_invitations;
create policy "Admins read manager invitations" on public.manager_invitations
  for select to authenticated using (public.is_active_admin());

create or replace function public.create_manager_invitation(invited_role text default 'junior')
returns text
language plpgsql security definer
set search_path = public
as $$
declare raw_token text := encode(extensions.gen_random_bytes(32), 'hex');
declare normalized_role text := lower(trim(replace(invited_role, '_', ' ')));
begin
  if not public.is_hierarchy_manager(auth.uid()) then
    raise exception 'Only Middle, Senior, Team Leader, or Manager accounts can invite employees' using errcode = '42501';
  end if;
  if normalized_role not in ('junior','middle','senior','team leader','telemarketing') then
    raise exception 'Unsupported invitation role';
  end if;
  insert into public.manager_invitations(token_hash, invited_by, invited_role)
  values (encode(extensions.digest(raw_token, 'sha256'), 'hex'), auth.uid(),
    case normalized_role when 'team leader' then 'team_leader' else normalized_role end);
  return raw_token;
end;
$$;

create or replace function public.redeem_manager_invitation(invitation_token text)
returns void
language plpgsql security definer
set search_path = public
as $$
declare inv public.manager_invitations%rowtype;
begin
  if auth.uid() is null then
    raise exception 'Sign in or complete registration before redeeming an invitation' using errcode = '42501';
  end if;
  select * into inv from public.manager_invitations
    where token_hash = encode(extensions.digest(invitation_token, 'sha256'), 'hex')
      and redeemed_at is null and expires_at > now()
    for update;
  if not found then
    raise exception 'Invitation is invalid, expired, or already used';
  end if;
  if inv.invited_by = auth.uid() then raise exception 'You cannot redeem your own invitation'; end if;
  update public.profiles
    set role = inv.invited_role::public.app_role
    where id = auth.uid() and lower(role) <> 'admin';
  if not found then raise exception 'Profile not found or protected'; end if;
  insert into public.manager_employee_assignments(manager_id, employee_id, created_by)
  values (inv.invited_by, auth.uid(), inv.invited_by)
  on conflict (manager_id, employee_id) do nothing;
  update public.manager_invitations set redeemed_by = auth.uid(), redeemed_at = now()
    where id = inv.id;
end;
$$;

-- Broaden assignment validation to the hierarchy roles while keeping admin protected.
drop policy if exists "Admins manage assignments" on public.manager_employee_assignments;
create policy "Admins manage assignments"
  on public.manager_employee_assignments for all to authenticated
  using (public.is_active_admin())
  with check (
    public.is_active_admin()
    and exists (select 1 from public.profiles m where m.id = manager_id and public.is_hierarchy_manager(m.id))
    and exists (select 1 from public.profiles e where e.id = employee_id and lower(e.role::text) <> 'admin' and e.active = true)
  );

drop policy if exists "Managers read own assignments" on public.manager_employee_assignments;
create policy "Managers read own assignments"
  on public.manager_employee_assignments for select to authenticated
  using (manager_id = auth.uid() or employee_id = auth.uid());

create or replace function public.is_assigned_manager(target_employee uuid)
returns boolean language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1 from public.manager_employee_assignments a
    where a.manager_id = auth.uid() and a.employee_id = target_employee
      and public.is_hierarchy_manager(a.manager_id)
  );
$$;

grant execute on function public.set_employee_role(uuid, text) to authenticated;
grant execute on function public.create_manager_invitation(text) to authenticated;
grant execute on function public.redeem_manager_invitation(text) to authenticated;


-- Return the caller's recursively assigned team without exposing unrelated profiles.
create or replace function public.get_my_team_hierarchy()
returns table(id uuid, email text, full_name text, role text, active boolean, manager_id uuid, depth integer)
language sql stable security definer
set search_path = public
as $$
  with recursive team as (
    select a.employee_id as id, a.manager_id, 1 as depth, array[auth.uid(), a.employee_id]::uuid[] as path
    from public.manager_employee_assignments a
    where a.manager_id = auth.uid()
    union all
    select a.employee_id, a.manager_id, t.depth + 1, t.path || a.employee_id
    from public.manager_employee_assignments a
    join team t on a.manager_id = t.id
    where t.depth < 12 and not a.employee_id = any(t.path)
  )
  select p.id, p.email, p.full_name, p.role, p.active, team.manager_id, team.depth
  from team join public.profiles p on p.id = team.id
  where exists (select 1 from public.profiles me where me.id = auth.uid() and me.active = true
    and (lower(me.role::text) = 'admin' or public.is_hierarchy_manager(me.id)))
  order by team.depth, p.full_name;
$$;

-- Managers may see attendance for any descendant in their assigned reporting tree.
create or replace function public.is_assigned_manager(target_employee uuid)
returns boolean language sql stable security definer
set search_path = public
as $$
  with recursive team(id, path, depth) as (
    select a.employee_id, array[auth.uid(), a.employee_id]::uuid[], 1
    from public.manager_employee_assignments a where a.manager_id = auth.uid()
    union all
    select a.employee_id, t.path || a.employee_id, t.depth + 1
    from public.manager_employee_assignments a
    join team t on a.manager_id = t.id
    where t.depth < 12 and not a.employee_id = any(t.path)
  )
  select exists (
    select 1 from team t join public.profiles me on me.id = auth.uid()
    where t.id = target_employee and me.active = true
      and (lower(me.role) = 'admin' or public.is_hierarchy_manager(me.id))
  );
$$;

grant execute on function public.get_my_team_hierarchy() to authenticated;
