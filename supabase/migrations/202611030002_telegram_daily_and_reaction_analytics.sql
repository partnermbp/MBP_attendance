-- Daily per-participant activity, reply/reaction response summaries,
-- and persistent reaction state for group chat rendering.

create table if not exists public.telegram_message_reactions (
  telegram_chat_id bigint not null references public.telegram_groups(telegram_chat_id) on delete cascade,
  telegram_message_id bigint not null,
  telegram_user_id bigint not null,
  username text,
  display_name text,
  reactions jsonb not null default '[]'::jsonb check (jsonb_typeof(reactions) = 'array'),
  reacted_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (telegram_chat_id, telegram_message_id, telegram_user_id)
);

create index if not exists telegram_message_reactions_chat_message_idx
  on public.telegram_message_reactions(telegram_chat_id, telegram_message_id);

create table if not exists public.telegram_message_reaction_counts (
  telegram_chat_id bigint not null references public.telegram_groups(telegram_chat_id) on delete cascade,
  telegram_message_id bigint not null,
  reactions jsonb not null default '[]'::jsonb check (jsonb_typeof(reactions) = 'array'),
  updated_at timestamptz not null default now(),
  primary key (telegram_chat_id, telegram_message_id)
);

create table if not exists public.telegram_message_reaction_events (
  id bigint generated by default as identity primary key,
  telegram_update_id bigint not null,
  telegram_chat_id bigint not null references public.telegram_groups(telegram_chat_id) on delete cascade,
  telegram_message_id bigint not null,
  telegram_user_id bigint,
  username text,
  display_name text,
  actor_chat_id bigint,
  actor_chat_title text,
  reaction_key text not null,
  reaction_label text not null,
  action text not null check (action in ('added', 'removed')),
  reacted_at timestamptz not null,
  response_seconds integer,
  created_at timestamptz not null default now(),
  unique (telegram_update_id, telegram_chat_id, telegram_message_id, reaction_key, action)
);

create index if not exists telegram_message_reaction_events_user_date_idx
  on public.telegram_message_reaction_events(telegram_chat_id, telegram_user_id, reacted_at desc)
  where action = 'added';

alter table public.telegram_message_reactions enable row level security;
alter table public.telegram_message_reaction_counts enable row level security;
alter table public.telegram_message_reaction_events enable row level security;

revoke all on public.telegram_message_reactions from anon, authenticated;
revoke all on public.telegram_message_reaction_counts from anon, authenticated;
revoke all on public.telegram_message_reaction_events from anon, authenticated;
grant select on public.telegram_message_reactions to authenticated;
grant select on public.telegram_message_reaction_counts to authenticated;
grant all on public.telegram_message_reactions to service_role;
grant all on public.telegram_message_reaction_counts to service_role;
grant all on public.telegram_message_reaction_events to service_role;
grant usage, select on sequence public.telegram_message_reaction_events_id_seq to service_role;

drop policy if exists "Authorized staff read Telegram message reactions" on public.telegram_message_reactions;
create policy "Authorized staff read Telegram message reactions"
  on public.telegram_message_reactions for select to authenticated
  using (
    public.is_active_admin()
    or exists (
      select 1 from public.telegram_group_members gm
      where gm.telegram_chat_id = telegram_message_reactions.telegram_chat_id
        and gm.profile_id is not null
        and public.is_assigned_manager(gm.profile_id)
    )
  );

drop policy if exists "Authorized staff read Telegram reaction counts" on public.telegram_message_reaction_counts;
create policy "Authorized staff read Telegram reaction counts"
  on public.telegram_message_reaction_counts for select to authenticated
  using (
    public.is_active_admin()
    or exists (
      select 1 from public.telegram_group_members gm
      where gm.telegram_chat_id = telegram_message_reaction_counts.telegram_chat_id
        and gm.profile_id is not null
        and public.is_assigned_manager(gm.profile_id)
    )
  );

create or replace function public.get_telegram_group_daily_user_activity(
  p_chat_id bigint,
  p_days integer default 7,
  p_timezone text default 'UTC'
)
returns table (
  telegram_user_id bigint,
  display_name text,
  username text,
  activity_date date,
  message_count bigint
)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_days integer := greatest(1, least(coalesce(p_days, 7), 30));
  v_timezone text := coalesce(nullif(p_timezone, ''), 'UTC');
begin
  if auth.uid() is null then
    raise exception 'Sign in is required.' using errcode = '42501';
  end if;

  if not exists (select 1 from pg_catalog.pg_timezone_names z where z.name = v_timezone) then
    v_timezone := 'UTC';
  end if;

  if p_chat_id is null or not (
    public.is_active_admin()
    or exists (
      select 1 from public.telegram_group_members gm
      where gm.telegram_chat_id = p_chat_id
        and gm.profile_id is not null
        and public.is_assigned_manager(gm.profile_id)
    )
  ) then
    raise exception 'You do not have access to this Telegram group.' using errcode = '42501';
  end if;

  return query
  select
    m.telegram_user_id,
    (array_agg(m.display_name order by m.message_date desc, m.telegram_message_id desc))[1],
    (array_agg(m.username order by m.message_date desc, m.telegram_message_id desc))[1],
    (m.message_date at time zone v_timezone)::date,
    count(*)::bigint
  from public.telegram_messages m
  where m.telegram_chat_id = p_chat_id
    and m.telegram_user_id is not null
    and m.is_deleted = false
    and (m.message_date at time zone v_timezone)::date
      between ((pg_catalog.now() at time zone v_timezone)::date - (v_days - 1))
          and (pg_catalog.now() at time zone v_timezone)::date
  group by m.telegram_user_id, (m.message_date at time zone v_timezone)::date
  order by (m.message_date at time zone v_timezone)::date, count(*) desc;
end;
$$;

create or replace function public.get_telegram_group_response_summary(
  p_chat_id bigint,
  p_days integer default 7
)
returns table (
  telegram_user_id bigint,
  display_name text,
  username text,
  reply_count bigint,
  avg_reply_seconds numeric,
  reaction_count bigint,
  avg_reaction_seconds numeric
)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_days integer := greatest(1, least(coalesce(p_days, 7), 30));
begin
  if auth.uid() is null then
    raise exception 'Sign in is required.' using errcode = '42501';
  end if;

  if p_chat_id is null or not (
    public.is_active_admin()
    or exists (
      select 1 from public.telegram_group_members gm
      where gm.telegram_chat_id = p_chat_id
        and gm.profile_id is not null
        and public.is_assigned_manager(gm.profile_id)
    )
  ) then
    raise exception 'You do not have access to this Telegram group.' using errcode = '42501';
  end if;

  return query
  with reply_stats as (
    select
      reply.telegram_user_id,
      count(*)::bigint as reply_count,
      avg(extract(epoch from (reply.message_date - question.message_date)))::numeric as avg_reply_seconds
    from public.telegram_messages reply
    join public.telegram_messages question
      on question.telegram_chat_id = reply.telegram_chat_id
     and question.telegram_message_id = reply.reply_to_message_id
    where reply.telegram_chat_id = p_chat_id
      and reply.telegram_user_id is not null
      and reply.reply_to_message_id is not null
      and reply.message_date >= pg_catalog.now() - pg_catalog.make_interval(days => v_days)
      and reply.message_date >= question.message_date
      and reply.telegram_user_id is distinct from question.telegram_user_id
      and reply.is_deleted = false
    group by reply.telegram_user_id
  ),
  reaction_stats as (
    select
      event.telegram_user_id,
      count(*)::bigint as reaction_count,
      avg(event.response_seconds)::numeric as avg_reaction_seconds
    from public.telegram_message_reaction_events event
    where event.telegram_chat_id = p_chat_id
      and event.telegram_user_id is not null
      and event.action = 'added'
      and event.reacted_at >= pg_catalog.now() - pg_catalog.make_interval(days => v_days)
    group by event.telegram_user_id
  ),
  people as (
    select telegram_user_id from reply_stats
    union
    select telegram_user_id from reaction_stats
  )
  select
    people.telegram_user_id,
    member.display_name,
    member.username,
    coalesce(reply_stats.reply_count, 0)::bigint,
    reply_stats.avg_reply_seconds,
    coalesce(reaction_stats.reaction_count, 0)::bigint,
    reaction_stats.avg_reaction_seconds
  from people
  left join public.telegram_group_members member
    on member.telegram_chat_id = p_chat_id
   and member.telegram_user_id = people.telegram_user_id
  left join reply_stats on reply_stats.telegram_user_id = people.telegram_user_id
  left join reaction_stats on reaction_stats.telegram_user_id = people.telegram_user_id
  order by coalesce(reply_stats.reply_count, 0) + coalesce(reaction_stats.reaction_count, 0) desc,
           people.telegram_user_id;
end;
$$;

revoke all on function public.get_telegram_group_daily_user_activity(bigint, integer, text) from public, anon;
grant execute on function public.get_telegram_group_daily_user_activity(bigint, integer, text) to authenticated;
revoke all on function public.get_telegram_group_response_summary(bigint, integer) from public, anon;
grant execute on function public.get_telegram_group_response_summary(bigint, integer) to authenticated;
